"""Binary report exports: DOCX and PDF, standard library only (the WebQ export menu).

Both render the same outline as the Markdown report: cover, summary, findings
(severity, title, check, CWE/OWASP, detail, fix) and the module table.

* DOCX is a minimal WordprocessingML package (document, styles, relationships),
  so Word, LibreOffice and Pages open it and the text stays editable.
* PDF uses the 14 standard fonts, so it needs no embedded font; those fonts only
  cover Latin-1. Other characters are replaced with ``?`` and the page says so;
  the HTML export keeps every script.
"""
from __future__ import annotations

import io
import zipfile
from typing import Dict, List, Tuple
from xml.sax.saxutils import escape

from .version import TOOL_NAME, VERSION

SEVERITIES = ("critical", "high", "medium", "low", "info")
Block = Tuple[str, str]  # (style, text): title, meta, h1, h2, body, mono, fix, row


def outline(document: Dict[str, object]) -> List[Block]:
    """The report as a flat list of styled text blocks."""
    cover = document.get("cover") or {}
    blocks: List[Block] = [("title", str(cover.get("title") or f"{TOOL_NAME} report — {document.get('target')}"))]
    byline = " · ".join(part for part in (
        f"Prepared for {cover['client']}" if cover.get("client") else "",
        f"by {cover['author']}" if cover.get("author") else "") if part)
    if byline:
        blocks.append(("meta", byline))
    blocks.append(("meta", f"Grade {document.get('grade')} · {document.get('score')}/100 · {document.get('url')} · "
                           f"scanned {document.get('started_at')} · preset {document.get('preset')}"
                           + (" · active" if document.get("active") else "")))
    if document.get("refused"):
        blocks.append(("body", f"The scan stopped: {document.get('refusal')}"))
    summary = document.get("summary") or {}
    blocks.append(("h1", "Summary"))
    blocks.append(("row", "   ".join(f"{severity} {summary.get(severity, 0)}" for severity in SEVERITIES)
                   + f"   total {summary.get('total', 0)}"))
    blocks.append(("h1", "Findings"))
    findings = document.get("findings") or []
    if not findings:
        blocks.append(("body", "No findings at this preset."))
    for finding in findings:
        label = " · ".join(str(part) for part in (finding.get("cwe"), finding.get("owasp")) if part)
        blocks.append(("h2", f"{str(finding.get('severity', '')).upper()} — {finding.get('title')}"))
        blocks.append(("meta", f"Check {finding.get('module')}" + (f" · {label}" if label else "")))
        if finding.get("detail"):
            blocks.append(("body", str(finding["detail"])))
        if finding.get("evidence"):
            blocks.append(("mono", str(finding["evidence"])))
        if finding.get("remediation"):
            blocks.append(("fix", f"Fix: {finding['remediation']}"))
    blocks.append(("h1", "Checks"))
    for module in document.get("modules") or []:
        note = module.get("note") or module.get("error") or ""
        blocks.append(("row", f"{module.get('label')} — {module.get('status')} · {module.get('findings')} finding(s) · "
                              f"{module.get('duration_ms')} ms" + (f" · {note}" if note else "")))
    blocks.append(("meta", f"Generated by {TOOL_NAME} {VERSION} — authorized testing only."))
    return blocks


# ── DOCX ─────────────────────────────────────────────────────────────────────

_CONTENT_TYPES = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
<Default Extension="xml" ContentType="application/xml"/>
<Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
<Override PartName="/word/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.styles+xml"/>
</Types>"""
_RELS = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>"""
_DOC_RELS = """<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
</Relationships>"""
_W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
_STYLES = f"""<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:styles xmlns:w="{_W}">
<w:style w:type="paragraph" w:default="1" w:styleId="Normal"><w:name w:val="Normal"/><w:pPr><w:spacing w:after="80"/></w:pPr><w:rPr><w:rFonts w:ascii="Calibri" w:hAnsi="Calibri" w:cs="Arial"/><w:sz w:val="21"/></w:rPr></w:style>
<w:style w:type="paragraph" w:styleId="Title"><w:name w:val="Title"/><w:basedOn w:val="Normal"/><w:pPr><w:spacing w:after="120"/></w:pPr><w:rPr><w:b/><w:sz w:val="40"/></w:rPr></w:style>
<w:style w:type="paragraph" w:styleId="Heading1"><w:name w:val="heading 1"/><w:basedOn w:val="Normal"/><w:pPr><w:keepNext/><w:spacing w:before="240" w:after="80"/><w:outlineLvl w:val="0"/></w:pPr><w:rPr><w:b/><w:sz w:val="30"/></w:rPr></w:style>
<w:style w:type="paragraph" w:styleId="Heading2"><w:name w:val="heading 2"/><w:basedOn w:val="Normal"/><w:pPr><w:keepNext/><w:spacing w:before="160" w:after="40"/><w:outlineLvl w:val="1"/></w:pPr><w:rPr><w:b/><w:sz w:val="24"/></w:rPr></w:style>
<w:style w:type="paragraph" w:styleId="Meta"><w:name w:val="Meta"/><w:basedOn w:val="Normal"/><w:rPr><w:color w:val="666666"/><w:sz w:val="18"/></w:rPr></w:style>
<w:style w:type="paragraph" w:styleId="Code"><w:name w:val="Code"/><w:basedOn w:val="Normal"/><w:rPr><w:rFonts w:ascii="Consolas" w:hAnsi="Consolas"/><w:sz w:val="18"/></w:rPr></w:style>
</w:styles>"""
_DOCX_STYLE = {"title": "Title", "meta": "Meta", "h1": "Heading1", "h2": "Heading2", "body": "Normal",
               "mono": "Code", "fix": "Normal", "row": "Normal"}


def _clean_xml(text: str) -> str:
    """XML 1.0 refuses most control characters; drop them rather than fail."""
    return "".join(char for char in text if char in "\t\n" or ord(char) >= 0x20)


def to_docx(document: Dict[str, object]) -> bytes:
    paragraphs = []
    for style, text in outline(document):
        bold = "<w:b/>" if style == "fix" else ""
        runs = "<w:r><w:br/></w:r>".join(
            f'<w:r><w:rPr>{bold}</w:rPr><w:t xml:space="preserve">{escape(_clean_xml(line))}</w:t></w:r>'
            for line in text.split("\n"))
        paragraphs.append(f'<w:p><w:pPr><w:pStyle w:val="{_DOCX_STYLE[style]}"/></w:pPr>{runs}</w:p>')
    body = (f'<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<w:document xmlns:w="{_W}"><w:body>'
            + "".join(paragraphs)
            + '<w:sectPr><w:pgSz w:w="11906" w:h="16838"/><w:pgMar w:top="1134" w:right="1134" w:bottom="1134" '
              'w:left="1134" w:header="567" w:footer="567" w:gutter="0"/></w:sectPr></w:body></w:document>')
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as package:
        package.writestr("[Content_Types].xml", _CONTENT_TYPES)
        package.writestr("_rels/.rels", _RELS)
        package.writestr("word/_rels/document.xml.rels", _DOC_RELS)
        package.writestr("word/styles.xml", _STYLES)
        package.writestr("word/document.xml", body)
    return buffer.getvalue()


# ── PDF ──────────────────────────────────────────────────────────────────────

_PAGE_W, _PAGE_H, _MARGIN = 595, 842, 50
_PDF_STYLE = {  # font resource, size, leading, space before
    "title": ("F2", 18, 24, 0), "meta": ("F1", 8.5, 12, 2), "h1": ("F2", 13, 18, 12),
    "h2": ("F2", 10.5, 14, 8), "body": ("F1", 9.5, 13, 2), "mono": ("F3", 8, 11, 2),
    "fix": ("F2", 9.5, 13, 2), "row": ("F1", 9, 12.5, 1),
}
_WIDTH_FACTOR = {"F1": 0.52, "F2": 0.56, "F3": 0.6}  # average glyph width / size, for wrapping


def _latin1(text: str) -> Tuple[str, bool]:
    swapped = {"—": "-", "–": "-", "·": "\xb7", "→": "->", "…": "...", "“": '"', "”": '"', "‘": "'", "’": "'"}
    out, lossy = [], False
    for char in text:
        char = swapped.get(char, char)
        if all(ord(part) < 256 for part in char):
            out.append(char)
        else:
            out.append("?")
            lossy = True
    return "".join(out), lossy


def _wrap(text: str, font: str, size: float) -> List[str]:
    limit = max(20, int((_PAGE_W - 2 * _MARGIN) / (size * _WIDTH_FACTOR[font])))
    lines: List[str] = []
    for raw in text.split("\n") or [""]:
        words, current = raw.split(" "), ""
        for word in words:
            while len(word) > limit:  # long tokens (hashes, URLs) are cut, not overflowed
                if current:
                    lines.append(current)
                    current = ""
                lines.append(word[:limit])
                word = word[limit:]
            candidate = f"{current} {word}" if current else word
            if len(candidate) > limit:
                lines.append(current)
                current = word
            else:
                current = candidate
        lines.append(current)
    return lines


def _pdf_string(text: str) -> str:
    return "(" + text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)").replace("\r", " ") + ")"


def to_pdf(document: Dict[str, object]) -> bytes:
    blocks = outline(document)
    lossy = False
    pages: List[List[str]] = [[]]
    y = _PAGE_H - _MARGIN
    for style, text in blocks:
        font, size, leading, before = _PDF_STYLE[style]
        text, changed = _latin1(text)
        lossy = lossy or changed
        y -= before
        for line in _wrap(text, font, size):
            if y - leading < _MARGIN:
                pages.append([])
                y = _PAGE_H - _MARGIN
            y -= leading
            pages[-1].append(f"BT /{font} {size} Tf {_MARGIN} {y:.1f} Td {_pdf_string(line)} Tj ET")
    if lossy:
        note = "Some characters are outside the PDF standard fonts and show as '?'; the HTML export keeps them."
        pages[-1].append(f"BT /F1 7.5 Tf {_MARGIN} {_MARGIN - 20} Td {_pdf_string(note)} Tj ET")
    for number, page in enumerate(pages, 1):
        page.append(f"BT /F1 7.5 Tf {_PAGE_W - _MARGIN - 40} {_MARGIN - 20} Td {_pdf_string(f'{number} / {len(pages)}')} Tj ET")

    objects: List[bytes] = []

    def add(body: bytes) -> int:
        objects.append(body)
        return len(objects)

    catalog = add(b"")  # placeholders, filled once the page ids are known
    page_tree = add(b"")
    fonts = [add(f"<< /Type /Font /Subtype /Type1 /BaseFont /{name} /Encoding /WinAnsiEncoding >>".encode())
             for name in ("Helvetica", "Helvetica-Bold", "Courier")]
    resources = f"<< /Font << /F1 {fonts[0]} 0 R /F2 {fonts[1]} 0 R /F3 {fonts[2]} 0 R >> >>"
    page_ids = []
    for page in pages:
        stream = "\n".join(page).encode("latin-1")
        content = add(b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream")
        page_ids.append(add(f"<< /Type /Page /Parent {page_tree} 0 R /MediaBox [0 0 {_PAGE_W} {_PAGE_H}] "
                            f"/Resources {resources} /Contents {content} 0 R >>".encode()))
    objects[catalog - 1] = f"<< /Type /Catalog /Pages {page_tree} 0 R >>".encode()
    objects[page_tree - 1] = (f"<< /Type /Pages /Kids [{' '.join(f'{pid} 0 R' for pid in page_ids)}] "
                              f"/Count {len(page_ids)} >>").encode()
    title, _ = _latin1(str((document.get("cover") or {}).get("title") or f"{TOOL_NAME} — {document.get('target')}"))
    info = add(f"<< /Title {_pdf_string(title)} /Producer {_pdf_string(f'{TOOL_NAME} {VERSION}')} >>".encode("latin-1"))

    out = io.BytesIO()
    out.write(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for index, body in enumerate(objects, 1):
        offsets.append(out.tell())
        out.write(b"%d 0 obj\n" % index + body + b"\nendobj\n")
    xref = out.tell()
    out.write(b"xref\n0 %d\n0000000000 65535 f \n" % (len(objects) + 1))
    for offset in offsets:
        out.write(b"%010d 00000 n \n" % offset)
    out.write(b"trailer\n<< /Size %d /Root %d 0 R /Info %d 0 R >>\nstartxref\n%d\n%%%%EOF\n"
              % (len(objects) + 1, catalog, info, xref))
    return out.getvalue()


BINARY_FORMATS = {"pdf": to_pdf, "docx": to_docx}

__all__ = ["BINARY_FORMATS", "outline", "to_docx", "to_pdf"]
